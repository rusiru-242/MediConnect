"""Patient profile data (R02, resolves A05-O1).

The mobile Profile screen used to show invented values (height, weight, BMI "Normal", a Penicillin allergy, an
emergency contact, insurance, blood type, age and sex). This service returns only stored, authorised data:

* ``healthProfile`` - values the patient entered themselves, stored under ``users.healthProfile`` and always labelled
  ``patient_reported``. Every field is optional; a missing value stays missing (no default is ever stored).
  ``allergyStatus`` distinguishes ``not_provided`` (nothing said), ``none_known`` (the patient explicitly reported no
  known allergies) and ``has_allergies`` (one or more listed).
* ``recordedAllergies`` - active allergy entries from the medical record (``patient_medical_records``), with their
  provenance (clinician-authored, patient-uploaded, imported). They are shown, never modified here.
* ``bmi`` - calculated only when both a height and a weight exist; a plain number with a note, never a category or
  diagnosis.

Nothing here is generated by an AI model.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from bson import ObjectId
from fastapi import HTTPException, status
from pydantic import BaseModel, ConfigDict, Field, field_validator
from pymongo.database import Database

ALLERGY_STATUSES = ("not_provided", "none_known", "has_allergies")
PHONE_RE = re.compile(r"^\+?[0-9][0-9 ()\-]{6,19}$")
CONTROL_RE = re.compile(r"[\x00-\x1f\x7f]")
BMI_NOTE = "Calculated from the height and weight you entered. It is not a diagnosis."
SOURCE_LABELS = {"clinician_authored": "Recorded by a clinician", "patient_uploaded": "From your uploaded records",
                 "imported": "Imported record", "ai_generated_draft": "Draft (not verified)"}


def _clean_text(value: Optional[str], field: str, max_len: int, min_len: int = 1) -> Optional[str]:
    if value is None:
        return None
    text = " ".join(str(value).split())
    if CONTROL_RE.search(text):
        raise ValueError(f"{field} contains invalid characters.")
    if not (min_len <= len(text) <= max_len):
        raise ValueError(f"{field} must be {min_len}-{max_len} characters.")
    return text


class EmergencyContact(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: str
    relationship: Optional[str] = None
    phone: str

    @field_validator("name")
    @classmethod
    def _name(cls, v):
        return _clean_text(v, "Emergency contact name", 100)

    @field_validator("relationship")
    @classmethod
    def _rel(cls, v):
        return _clean_text(v, "Relationship", 40) if v not in (None, "") else None

    @field_validator("phone")
    @classmethod
    def _phone(cls, v):
        text = " ".join(str(v).split())
        if not PHONE_RE.match(text):
            raise ValueError("Enter a valid phone number (digits, spaces, +, -, brackets).")
        return text


class ProfileUpdate(BaseModel):
    """Fields a patient may change. Omitted fields are untouched; an explicit null clears the value."""

    model_config = ConfigDict(extra="forbid")
    fullName: Optional[str] = None
    heightCm: Optional[float] = Field(default=None, ge=50, le=250)
    weightKg: Optional[float] = Field(default=None, ge=2, le=350)
    allergyStatus: Optional[str] = None
    allergies: Optional[List[str]] = None
    emergencyContact: Optional[EmergencyContact] = None

    @field_validator("fullName")
    @classmethod
    def _full_name(cls, v):
        return _clean_text(v, "Full name", 100, 2) if v is not None else None

    @field_validator("allergyStatus")
    @classmethod
    def _status(cls, v):
        if v is not None and v not in ALLERGY_STATUSES:
            raise ValueError("allergyStatus must be not_provided, none_known or has_allergies.")
        return v

    @field_validator("allergies")
    @classmethod
    def _allergies(cls, v):
        if v is None:
            return None
        if len(v) > 20:
            raise ValueError("List at most 20 allergies.")
        cleaned: List[str] = []
        for item in v:
            text = _clean_text(item, "Allergy", 80)
            if text and text.lower() not in {c.lower() for c in cleaned}:
                cleaned.append(text)
        return cleaned


def _user_query(user_id: str) -> Dict[str, Any]:
    if ObjectId.is_valid(user_id):
        return {"$or": [{"_id": ObjectId(user_id)}, {"_id": user_id}]}
    return {"_id": user_id}


def _require_patient(user) -> str:
    role = getattr(user, "role", None)
    if str(getattr(role, "value", role) or "").upper() != "PATIENT":
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Only patients have a patient profile.")
    return str(user.id)


def bmi(height_cm: Optional[float], weight_kg: Optional[float]) -> Optional[float]:
    if not height_cm or not weight_kg or not (50 <= height_cm <= 250) or not (2 <= weight_kg <= 350):
        return None
    return round(weight_kg / ((height_cm / 100) ** 2), 1)


def _view(db: Database, doc: Dict[str, Any], user_id: str) -> Dict[str, Any]:
    hp = doc.get("healthProfile") or {}
    recorded = []
    for rec in db["patient_medical_records"].find(
            {"patientUserId": user_id, "recordType": "allergy", "status": "active"},
            {"title": 1, "clinicalData": 1, "sourceType": 1, "clinicalDate": 1}).sort("clinicalDate", -1).limit(50):
        name = rec.get("title") or (rec.get("clinicalData") or {}).get("allergen")
        if name:
            recorded.append({"allergen": name, "severity": (rec.get("clinicalData") or {}).get("severity"),
                             "source": rec.get("sourceType"),
                             "sourceLabel": SOURCE_LABELS.get(rec.get("sourceType"), "Medical record"),
                             "clinicalDate": rec.get("clinicalDate")})
    height, weight = hp.get("heightCm"), hp.get("weightKg")
    value = bmi(height, weight)
    return {
        "fullName": doc.get("fullName"),
        "email": doc.get("email"),
        "phone": doc.get("phone"),
        "profileImage": doc.get("profileImage"),
        "healthProfile": {
            "heightCm": height,
            "weightKg": weight,
            "bmi": value,
            "bmiNote": BMI_NOTE if value is not None else None,
            "allergyStatus": hp.get("allergyStatus") or "not_provided",
            "allergies": list(hp.get("allergies") or []),
            "emergencyContact": hp.get("emergencyContact"),
            "source": "patient_reported",
            "updatedAt": hp.get("updatedAt"),
        },
        "recordedAllergies": recorded,
    }


def get_profile(db: Database, user) -> Dict[str, Any]:
    user_id = _require_patient(user)
    doc = db["users"].find_one(_user_query(user_id), {"fullName": 1, "email": 1, "phone": 1, "profileImage": 1,
                                                      "healthProfile": 1})
    if not doc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Account not found.")
    return _view(db, doc, user_id)


def update_profile(db: Database, user, body: ProfileUpdate) -> Dict[str, Any]:
    user_id = _require_patient(user)
    doc = db["users"].find_one(_user_query(user_id), {"healthProfile": 1})
    if not doc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Account not found.")
    sent = body.model_fields_set
    hp = dict(doc.get("healthProfile") or {})
    for field in ("heightCm", "weightKg"):
        if field in sent:
            hp[field] = getattr(body, field)
    if "emergencyContact" in sent:
        hp["emergencyContact"] = body.emergencyContact.model_dump() if body.emergencyContact else None
    if "allergyStatus" in sent or "allergies" in sent:
        status_value = body.allergyStatus if "allergyStatus" in sent else hp.get("allergyStatus", "not_provided")
        status_value = status_value or "not_provided"
        items = body.allergies if "allergies" in sent else hp.get("allergies") or []
        items = items or []
        if status_value == "has_allergies" and not items:
            raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                                detail="List at least one allergy, or choose 'No known allergies' or 'Not provided'.")
        if status_value != "has_allergies" and items:
            raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                                detail="Allergies can only be listed when the status is 'has_allergies'.")
        hp["allergyStatus"], hp["allergies"] = status_value, items
    now = datetime.now(timezone.utc)
    hp["source"], hp["updatedAt"] = "patient_reported", now
    update: Dict[str, Any] = {"healthProfile": hp, "updatedAt": now}
    if "fullName" in sent:
        if not body.fullName:
            raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="Full name cannot be empty.")
        update["fullName"] = body.fullName
    db["users"].update_one(_user_query(user_id), {"$set": update})
    return get_profile(db, user)
