def test_doctor_verification_document_encrypted_and_each_view_audited(db, tmp_path):
    from app.services.document_storage_service import document_storage
    from fastapi import UploadFile
    import asyncio
    import io
    from starlette.datastructures import Headers
    user_id = str(ObjectId())
    upload = UploadFile(file=io.BytesIO(PDF), filename="licence.pdf",
                        headers=Headers({"content-type": "application/pdf"}))
    meta = asyncio.run(document_storage.save_document(upload, "medicalLicense", user_id))
    assert meta["encrypted"] is True and meta["encryptionKeyId"] == "test-session"
    on_disk = document_storage.get_document_path(meta["storagePath"]).read_bytes()
    assert dc.is_encrypted(on_disk) and b"%PDF" not in on_disk

    prof = ObjectId()
    db["doctor_profiles"].insert_one({"_id": prof, "userId": user_id, "verificationStatus": "PENDING",
                                      "medicalRegistrationNumber": f"SLMC-P05-{prof}", "doctorId": f"DOC-P05-{prof}",
                                      "verificationDocuments": {"medicalLicense": meta}})
    admin = _admin(db)
    res = client.get(f"/api/admin/doctors/applications/{prof}/documents/medicalLicense", headers=_auth(admin))
    assert res.status_code == 200 and res.content == PDF and res.headers["cache-control"] == "no-store"
    audit = db["admin_audit_logs"].find_one({"actionType": "DOCTOR_DOCUMENT_VIEWED", "targetId": str(prof)})
    assert audit and audit["actorId"] == admin["id"]
    patient = _make_test_patient(db, "P05DVP")
    assert client.get(f"/api/admin/doctors/applications/{prof}/documents/medicalLicense",
                      headers=_auth(patient)).status_code == 403


def test_migration_script_dry_run_apply_rotate_revert(tmp_path, monkeypatch):
    from scripts.encrypt_existing_documents import run
    store = tmp_path / "medical_documents" / "patientX"
    store.mkdir(parents=True)
    (store / "a.pdf").write_bytes(PDF)
    (store / "b.pdf").write_bytes(PDF + b"b")
    first = f"m1:{base64.b64encode(os.urandom(32)).decode()}"
    monkeypatch.setenv("DOCUMENT_ENCRYPTION_KEYS", first)
    assert run(tmp_path, "dry-run") == {"mode": "dry-run", "plaintext": 2, "encrypted": 0, "changed": 0, "failed": 0}
    assert (store / "a.pdf").read_bytes() == PDF  # dry run changes nothing
    assert run(tmp_path, "apply")["changed"] == 2
    assert dc.is_encrypted((store / "a.pdf").read_bytes())
    assert run(tmp_path, "apply")["changed"] == 0  # idempotent
    monkeypatch.setenv("DOCUMENT_ENCRYPTION_KEYS", f"m2:{base64.b64encode(os.urandom(32)).decode()},{first}")
    assert run(tmp_path, "rotate")["changed"] == 2
    assert dc.key_id_of((store / "a.pdf").read_bytes()) == "m2"
    assert run(tmp_path, "revert")["changed"] == 2
    assert (store / "a.pdf").read_bytes() == PDF and (store / "b.pdf").read_bytes() == PDF + b"b"
    assert not list(tmp_path.rglob("*.tmp-enc"))


