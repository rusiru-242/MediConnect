def _upload(patient, content=PDF, name="lab.pdf"):
    return client.post("/api/clinical/records/documents/upload", headers=_auth(patient),
                       files={"file": (name, content, "application/pdf")},
                       data={"title": "Synthetic lab report", "recordType": "laboratory_result", "clinicalDate": "2026-11-20"})


def test_medical_document_is_encrypted_on_disk_and_served_only_to_authorised_users(db):
    patient = _make_test_patient(db, "P05ENC")
    res = _upload(patient)
    assert res.status_code == 201, res.text
    record = db["patient_medical_records"].find_one({"patientUserId": patient["id"]})
    path = _get_storage_root() / record["documentMetadata"]["fileKey"]
    on_disk = path.read_bytes()
    assert dc.is_encrypted(on_disk) and b"%PDF" not in on_disk and b"synthetic Phase 05" not in on_disk

    rid = record["recordId"]
    got = client.get(f"/api/clinical/records/{rid}/download", headers=_auth(patient))
    assert got.status_code == 200 and got.content == PDF
    assert got.headers["cache-control"] == "no-store"

    treating, unrelated, admin = _make_test_doctor(db, "P05ENCD"), _make_test_doctor(db, "P05ENCX"), _admin(db)
    db["appointments"].insert_one({"patientUserId": patient["id"], "doctorUserId": treating["id"],
                                   "status": "CONFIRMED", "appointmentDate": "2026-11-21"})
    assert client.get(f"/api/clinical/records/{rid}/download", headers=_auth(treating)).content == PDF
    assert client.get(f"/api/clinical/records/{rid}/download", headers=_auth(unrelated)).status_code == 403
    assert client.get(f"/api/clinical/records/{rid}/download", headers=_auth(admin)).status_code == 403
    other = _make_test_patient(db, "P05ENCO")
    assert client.get(f"/api/clinical/records/{rid}/download", headers=_auth(other)).status_code == 403


def test_tampered_stored_document_is_refused_without_leaking_details(db):
    patient = _make_test_patient(db, "P05TAMP")
    assert _upload(patient).status_code == 201
    record = db["patient_medical_records"].find_one({"patientUserId": patient["id"]})
    path = _get_storage_root() / record["documentMetadata"]["fileKey"]
    blob = bytearray(path.read_bytes())
    blob[-3] ^= 0xFF
    path.write_bytes(bytes(blob))
    res = client.get(f"/api/clinical/records/{record['recordId']}/download", headers=_auth(patient))
    assert res.status_code == 500 and "integrity" in res.json()["detail"] and "Traceback" not in res.text


